/**
 * DSH pentest v2 — pure state kernel.
 *
 * 规则：
 * - 所有函数无副作用，不读时间以外外部状态；`now` 必须由调用方传入。
 * - 任何非法迁移抛 StateError，调用方不得写回。
 * - 一次 reduce 只产生一个新 state + 一个结果；UI 只从 state 投影。
 */

import { reduceV3State } from './state-v3-bridge.js';

export class StateError extends Error {
  constructor(code, message) {
    super(message);
    this.name = 'StateError';
    this.code = code;
  }
}

export const INTENT_STATES = new Set(['open', 'running', 'done', 'exhausted', 'blocked', 'stopped']);
export const INTENT_TERMINAL = new Set(['done', 'exhausted', 'blocked', 'stopped']);
export const TASK_STATES = new Set(['pending', 'claimed', 'running', 'done', 'failed', 'dead']);
export const TASK_ACTIVE = new Set(['pending', 'claimed', 'running']);
export const GOAL_PHASES = new Set(['active', 'proven', 'blocked', 'completed', 'stopped']);
export const FINDING_SEVERITIES = new Set(['critical', 'high', 'medium', 'low', 'info']);
export const ASSET_TYPES = new Set(['root-domain', 'subdomain', 'ip', 'service', 'app', 'endpoint']);

const ID_RE = /^[a-z][a-z0-9-]*-\d+$/;

function fail(code, message) {
  throw new StateError(code, message);
}

function assertState(state) {
  if (!state || state.version !== 2) fail('state/version', 'not a v2 pentest state');
  if (!state.sessionId) fail('state/session', 'state.sessionId missing');
  return state;
}

function nextId(state, kind) {
  const current = state.counters?.[kind] ?? 0;
  const id = `${kind}-${current + 1}`;
  state.counters = { ...(state.counters || {}), [kind]: current + 1 };
  return id;
}

function requireGoal(state) {
  if (!state.goal) fail('goal/missing', 'pentest engagement is not initialized; call pentest_add_goal first');
  return state.goal;
}

function requireIntent(state, intentId) {
  const intent = state.intents.find((item) => item.id === intentId);
  if (!intent) fail('intent/unknown', `unknown intent ${intentId}`);
  return intent;
}

function intentKindOf(intent) {
  return INTENT_KINDS.has(intent?.kind) ? intent.kind : 'recon';
}

function isVerificationIntent(intent) {
  return FINDING_INTENT_KINDS.has(intentKindOf(intent));
}

/**
 * 每个 finding 必须由**自己专属的**自动 verify intent 产出，绝不共用。
 * 调用方传来源 intent/fact 时，用它作为 derived_from 父节点；每次调用都新建
 * 一个 autoGenerated verify intent，保证「一个 intent 只对应一个 finding」。
 */
function ensureVerificationIntent(state, { sourceIntentId, fromFactId, title, now }) {
  const sourceIntent = sourceIntentId ? requireIntent(state, sourceIntentId) : null;
  const fact = fromFactId ? state.facts.find((item) => item.id === String(fromFactId)) : null;
  if (fromFactId && !fact) fail('finding/fact', `unknown source fact ${fromFactId}`);

  const sourceId = fact ? fact.id : (sourceIntent ? sourceIntent.id : (state.goal?.id || ''));
  const intent = {
    id: nextId(state, 'intent'),
    title: `验证：${String(title || '').slice(0, 78)}`,
    detail: '独立验证该结论，并保存可复现的完整 HTTP 请求包。',
    doneWhen: '结论被请求/响应证据证实或否证',
    kind: 'verify',
    state: 'done',
    stateReason: 'finding recorded',
    priority: 3,
    dependsOn: [],
    autoGenerated: true,
    ...(fact ? { sourceFactId: fact.id } : {}),
    createdAt: now,
    updatedAt: now
  };
  state.intents.push(intent);
  if (sourceId) pushEdge(state, 'derived_from', sourceId, intent.id, now);
  return intent;
}

function requireTask(state, taskId) {
  const task = state.queue.find((item) => item.id === taskId);
  if (!task) fail('task/unknown', `unknown queue task ${taskId}`);
  return task;
}

function activeTasksOfWorker(state, workerId) {
  return state.queue.filter((task) => TASK_ACTIVE.has(task.state) && task.state !== 'pending' && task.workerId === workerId);
}

function activeTaskOfIntent(state, intentId) {
  return state.queue.find((task) => task.intentId === intentId && TASK_ACTIVE.has(task.state));
}

function refreshIntentFromTasks(state, intentId, now) {
  const intent = state.intents.find((item) => item.id === intentId);
  if (!intent) return;
  const tasks = state.queue.filter((task) => task.intentId === intentId);
  if (tasks.length === 0) return;
  const executing = tasks.some((task) => task.state === 'claimed' || task.state === 'running');
  if (executing) {
    if (intent.state === 'open') intent.state = 'running';
    intent.updatedAt = now;
    return;
  }
  if (tasks.some((task) => task.state === 'done')) {
    intent.state = 'done';
    intent.stateReason = intent.stateReason || 'all queue tasks done';
  } else if (tasks.some((task) => task.state === 'dead')) {
    intent.state = 'blocked';
    intent.stateReason = intent.stateReason || 'queue tasks dead';
  } else if (intent.state === 'running') {
    intent.state = 'open';
    intent.stateReason = 'queue task requeued';
  }
  intent.updatedAt = now;
}

function normalizeText(value) {
  return String(value ?? '').trim();
}

function factKey(fact) {
  return [String(fact.kind || 'info'), normalizeText(fact.target), normalizeText(fact.detail).toLowerCase()].join('\u0000');
}

function edgeExists(state, kind, sourceId, targetId) {
  return state.edges.some((edge) => edge.kind === kind && edge.sourceId === sourceId && edge.targetId === targetId);
}

function pushEdge(state, kind, sourceId, targetId, now) {
  if (edgeExists(state, kind, sourceId, targetId)) return state.edges.find((edge) => edge.kind === kind && edge.sourceId === sourceId && edge.targetId === targetId);
  const edge = { id: nextId(state, 'edge'), kind, sourceId, targetId, createdAt: now };
  state.edges.push(edge);
  return edge;
}

export function createState({ sessionId, target = '', objective = '', authorization = '', workdir = '', targets = [], excludedTargets = [], now = Date.now() }) {
  if (!sessionId) fail('state/session', 'sessionId required');
  const goal = {
    id: nextId({ counters: { ...{} } }, 'goal'),
    target: normalizeText(target),
    objective: normalizeText(objective),
    authorization: String(authorization ?? ''),
    workdir: String(workdir ?? ''),
    targets: stringList(targets),
    excludedTargets: stringList(excludedTargets),
    phase: 'active',
    proofs: [],
    createdAt: now,
    updatedAt: now
  };
  // nextId above needs a state-like object; build goal id directly for simplicity
  goal.id = 'goal-1';
  return {
    version: 2,
    revision: 1,
    sessionId,
    goal,
    intents: [],
    facts: [],
    findings: [],
    assets: [],
    edges: [],
    digests: [],
    coverage: [],
    queue: [],
    counters: { goal: 1, intent: 0, fact: 0, finding: 0, asset: 0, edge: 0, digest: 0, task: 0 },
    jobs: {}
  };
}

function cloneState(state) {
  return structuredClone(state);
}

function assertIntentTransition(from, to) {
  if (!INTENT_STATES.has(to)) fail('intent/state', `unknown intent state ${to}`);
  if (INTENT_TERMINAL.has(from)) fail('intent/terminal', `intent is already ${from}; cannot move to ${to}`);
  if (from === 'open' && to === 'running') return;
  if (from === 'running' && INTENT_TERMINAL.has(to)) return;
  if (from === 'open' && INTENT_TERMINAL.has(to)) return;
  if (from === 'blocked' && to === 'open') return;
  fail('intent/transition', `invalid intent transition ${from} -> ${to}`);
}

function applyIntent(state, cmd, now) {
  switch (cmd.op) {
    case 'add': {
      requireGoal(state);
      const title = normalizeText(cmd.title);
      if (!title) fail('intent/title', 'intent title required');
      const duplicate = state.intents.find((intent) => normalizeText(intent.title) === title && !INTENT_TERMINAL.has(intent.state));
      if (duplicate) fail('intent/duplicate', `intent "${title}" already exists as ${duplicate.id}`);
      const dependsOn = Array.isArray(cmd.dependsOn) ? cmd.dependsOn.filter((id) => typeof id === 'string' && id !== '') : [];
      for (const dep of dependsOn) requireIntent(state, dep);
      const kind = INTENT_KINDS.has(cmd.kind) ? cmd.kind : 'recon';
      const intent = {
        id: nextId(state, 'intent'),
        title,
        detail: String(cmd.detail ?? ''),
        doneWhen: String(cmd.doneWhen ?? ''),
        kind,
        state: 'open',
        stateReason: '',
        priority: Number.isFinite(cmd.priority) ? cmd.priority : 5,
        dependsOn,
        createdAt: now,
        updatedAt: now
      };
      state.intents.push(intent);
      if (cmd.fromFactId) {
        const fact = state.facts.find((item) => item.id === String(cmd.fromFactId));
        if (!fact) fail('intent/fact', `unknown source fact ${cmd.fromFactId}`);
        pushEdge(state, 'derived_from', fact.id, intent.id, now);
      }
      return intent;
    }
    case 'set': {
      const intent = requireIntent(state, String(cmd.id || ''));
      assertIntentTransition(intent.state, String(cmd.state || ''));
      intent.state = String(cmd.state);
      intent.stateReason = String(cmd.reason ?? '');
      intent.updatedAt = now;
      return intent;
    }
    default:
      fail('intent/op', `unknown intent op ${cmd.op}`);
  }
}

function applyFact(state, cmd, now) {
  requireGoal(state);
  const intentId = String(cmd.intentId || '');
  if (intentId) requireIntent(state, intentId);
  const detail = String(cmd.detail ?? '');
  if (!normalizeText(detail)) fail('fact/detail', 'fact detail required');
  const candidate = {
    intentId,
    kind: String(cmd.kind || 'info'),
    target: String(cmd.target ?? ''),
    detail
  };
  const key = factKey(candidate);
  const duplicate = state.facts.find((fact) => factKey(fact) === key);
  if (duplicate) {
    if (intentId && intentId !== duplicate.intentId) pushEdge(state, 'yields', intentId, duplicate.id, now);
    return { fact: duplicate, reused: true };
  }
  const fact = {
    id: nextId(state, 'fact'),
    intentId,
    kind: candidate.kind,
    target: candidate.target,
    detail,
    confidence: cmd.confidence ?? 'medium',
    evidenceRefs: Array.isArray(cmd.evidenceRefs) ? cmd.evidenceRefs.filter((item) => typeof item === 'string' && item !== '') : [],
    author: String(cmd.author ?? ''),
    createdAt: now
  };
  state.facts.push(fact);
  if (intentId) pushEdge(state, 'yields', intentId, fact.id, now);
  return { fact, reused: false };
}

function applyAsset(state, cmd, now) {
  requireGoal(state);
  const value = normalizeText(cmd.value);
  if (!value) fail('asset/value', 'asset value required');
  const existing = state.assets.find((asset) => normalizeText(asset.value).toLowerCase() === value.toLowerCase());
  if (existing) return { asset: existing, reused: true };
  const type = String(cmd.assetType || 'endpoint');
  if (!ASSET_TYPES.has(type)) fail('asset/type', `unknown asset type ${type}`);
  if (cmd.parentId) {
    const parent = state.assets.find((asset) => asset.id === cmd.parentId);
    if (!parent) fail('asset/parent', `unknown parent asset ${cmd.parentId}`);
  }
  const asset = {
    id: nextId(state, 'asset'),
    type,
    value,
    meta: String(cmd.meta ?? ''),
    inScope: typeof cmd.inScope === 'boolean' ? cmd.inScope : true,
    author: String(cmd.author ?? ''),
    createdAt: now
  };
  state.assets.push(asset);
  if (cmd.parentId) {
    asset.parentId = cmd.parentId;
    pushEdge(state, 'parent', cmd.parentId, asset.id, now);
  }
  return { asset, reused: false };
}

function applyCoverage(state, cmd, now) {
  requireGoal(state);
  const surface = normalizeText(cmd.surface);
  const riskArea = normalizeText(cmd.riskArea);
  if (!surface || !riskArea) fail('coverage/args', 'coverage requires surface and riskArea');
  const row = {
    id: nextId(state, 'coverage'),
    surface,
    riskArea,
    outcome: String(cmd.outcome || 'no_issue_found'),
    evidence: String(cmd.evidence ?? ''),
    author: String(cmd.author ?? ''),
    createdAt: now
  };
  state.coverage.push(row);
  return row;
}

function applyDigest(state, cmd, now) {
  requireGoal(state);
  const title = normalizeText(cmd.title);
  if (!title) fail('digest/title', 'digest title required');
  const factIds = Array.isArray(cmd.factIds) ? cmd.factIds.filter((id) => typeof id === 'string' && id !== '') : [];
  for (const id of factIds) {
    if (!state.facts.some((fact) => fact.id === id)) fail('digest/fact', `unknown fact ${id}`);
  }
  const digest = {
    id: nextId(state, 'digest'),
    title,
    summary: String(cmd.summary ?? ''),
    factIds,
    createdAt: now
  };
  state.digests.push(digest);
  return digest;
}

const FINDING_EVIDENCE_STATUSES = new Set(['confirmed', 'likely', 'unverified']);
const INTENT_KINDS = new Set(['recon', 'verify', 'exploit', 'report']);
const FINDING_INTENT_KINDS = new Set(['verify', 'exploit']);
const HTTP_PACKET_RE = /(?:^|\n)\s*(?:GET|POST|PUT|DELETE|PATCH|HEAD|OPTIONS|TRACE|CONNECT)\s+\S+\s+HTTP\/1\.[01][\s\S]*?\nHost:[^\n]+/i;

function stringList(value) {
  return Array.isArray(value) ? value.filter((item) => typeof item === 'string' && item !== '') : [];
}

function textOf(value) {
  return value === undefined || value === null ? '' : String(value);
}

function normalizeEvidenceStatus(value) {
  const raw = textOf(value).trim().toLowerCase();
  if (['confirmed', 'verified', 'reproduced', '已验证', '已确认', '已复现'].includes(raw)) return 'confirmed';
  if (['likely', 'probable', '很可能', '强证据'].includes(raw)) return 'likely';
  if (raw === '' || raw === 'unverified' || raw === '待验证' || raw === '疑似') return raw === '' ? 'likely' : 'unverified';
  return raw;
}

function findingFields(cmd) {
  const steps = stringList(cmd.reproducibleSteps ?? cmd.steps);
  return {
    dedupeKey: normalizeText(cmd.dedupeKey || ''),
    description: textOf(cmd.description),
    evidenceStatus: normalizeEvidenceStatus(cmd.evidenceStatus),
    impactProven: textOf(cmd.impactProven || 'none'),
    evidenceRefs: stringList(cmd.evidenceRefs),
    apiSources: stringList(cmd.apiSources ?? cmd.interfaceSources ?? cmd.sourceFiles ?? cmd.sources),
    stepNotes: stringList(cmd.stepNotes ?? cmd.stepExplanations ?? cmd.stepNotesByIndex),
    stepResponses: stringList(cmd.stepResponses ?? cmd.stepResponseBodies ?? cmd.stepResponsesByIndex),
    stepExpected: stringList(cmd.stepExpected ?? cmd.stepExpectedByIndex),
    trafficRef: textOf(cmd.trafficRef),
    report: textOf(cmd.report),
    reproducibleSteps: steps,
    steps,
    remediation: textOf(cmd.remediation),
    riskAnalysis: textOf(cmd.riskAnalysis),
    affectedAssetId: textOf(cmd.affectedAssetId),
    affectedAssets: stringList(cmd.affectedAssets),
    poc: textOf(cmd.poc),
    counterevidence: textOf(cmd.counterevidence),
    confidence: Number.isFinite(cmd.confidence) ? cmd.confidence : undefined,
    noAssetReason: textOf(cmd.noAssetReason),
    preconditions: textOf(cmd.preconditions),
    scope: textOf(cmd.scope),
    impactEvidence: textOf(cmd.impactEvidence),
    validation: cmd.validation && typeof cmd.validation === 'object' ? structuredClone(cmd.validation) : undefined,
    retest: cmd.retest && typeof cmd.retest === 'object' ? structuredClone(cmd.retest) : undefined,
    duplicateReports: Number.isFinite(cmd.duplicateReports) ? cmd.duplicateReports : 0
  };
}

function assertReportReadySteps(steps) {
  if (!Array.isArray(steps) || steps.length === 0) {
    fail('finding/steps', 'reproducibleSteps is required: the report must contain complete raw HTTP request packets that Burp can replay');
  }
  for (const step of steps) {
    if (!HTTP_PACKET_RE.test(String(step))) {
      fail('finding/steps', 'each reproducible step must contain a complete raw HTTP request (request line + Host header + headers/body); do not omit the packet');
    }
  }
}

function applyFinding(state, cmd, now) {
  requireGoal(state);
  if (cmd.op === 'update') return updateFinding(state, cmd, now);
  if (cmd.op === 'delete') {
    const target = state.findings.find((finding) => finding.id === String(cmd.id || '') && !finding.deleted);
    if (!target) fail('finding/not-found', `unknown finding ${String(cmd.id || '')}`);
    target.deleted = true;
    target.deletedReason = textOf(cmd.reason);
    target.updatedAt = now;
    return { id: target.id, deleted: true };
  }
  const title = normalizeText(cmd.title);
  if (!title) fail('finding/title', 'finding title required');
  const dedupeKey = normalizeText(cmd.dedupeKey || title);
  const duplicate = state.findings.find((finding) => !finding.deleted && (normalizeText(finding.title) === title || normalizeText(finding.dedupeKey || finding.title) === dedupeKey));
  if (duplicate) fail('finding/duplicate', `finding title/dedupeKey "${title}" already exists as ${duplicate.id}; merge affectedAssets into the existing finding instead of creating a duplicate`);
  const severity = String(cmd.severity || 'medium');
  if (!FINDING_SEVERITIES.has(severity)) fail('finding/severity', `unknown severity ${severity}`);
  const fields = findingFields(cmd);
  assertReportReadySteps(fields.reproducibleSteps);
  const explicitIntentId = String(cmd.intentId || '');
  if (explicitIntentId) requireIntent(state, explicitIntentId);
  const verificationIntent = ensureVerificationIntent(state, {
    sourceIntentId: explicitIntentId || undefined,
    fromFactId: cmd.fromFactId ? String(cmd.fromFactId) : undefined,
    title,
    now
  });
  const intentId = verificationIntent.id;
  const finding = {
    id: nextId(state, 'finding'),
    intentId,
    title,
    severity,
    dedupeKey: dedupeKey || undefined,
    ...fields,
    createdAt: now,
    updatedAt: now
  };
  state.findings.push(finding);
  if (cmd.fromFactId) pushEdge(state, 'derived_from', String(cmd.fromFactId), finding.id, now);
  pushEdge(state, 'proves', intentId, finding.id, now);
  return finding;
}

/**
 * 存量修复：把挂在侦察/宽 intent 下的 finding 迁到独立的验证 intent。
 * 幂等；返回是否发生变化。真实保存由 store 层负责。
 */
export function repairFindingLineage(state, now = Date.now()) {
  if (!state || !Array.isArray(state.findings) || !Array.isArray(state.intents)) return false;
  let changed = false;
  const autoIds = new Set();

  function inferKind(intent) {
    const title = String(intent?.title || '');
    if (/^(验证|verify)\s*[:：]/i.test(title)) return 'verify';
    if (/(?:验证|利用|越权|注入|上传|RCE|代码执行|攻击|泄露|绕过|读取|写入)/i.test(title)) return 'verify';
    return 'recon';
  }

  // 1) 旧状态补字段：kind 缺失的按标题推断；autoGenerated 明确化。
  for (const intent of state.intents) {
    if (!INTENT_KINDS.has(intent.kind)) {
      intent.kind = inferKind(intent);
      changed = true;
    }
    if (intent.autoGenerated === undefined) {
      intent.autoGenerated = /^(验证|verify)\s*[:：]/i.test(String(intent.title || ''));
      changed = true;
    }
    if (intent.autoGenerated === true) autoIds.add(intent.id);
  }

  const activeFindings = state.findings.filter((finding) => finding.deleted !== true);
  const countByIntent = new Map();
  for (const finding of activeFindings) {
    countByIntent.set(finding.intentId, (countByIntent.get(finding.intentId) || 0) + 1);
  }
  const keptAuto = new Set();

  const sourceOfAuto = (intent) => {
    if (!intent) return { sourceIntentId: '', fromFactId: '' };
    const derived = state.edges.find((edge) => edge.kind === 'derived_from' && edge.targetId === intent.id);
    if (!derived) return { sourceIntentId: intent.id, fromFactId: '' };
    if (String(derived.sourceId).startsWith('fact-')) return { sourceIntentId: '', fromFactId: derived.sourceId };
    return { sourceIntentId: derived.sourceId, fromFactId: '' };
  };

  for (const finding of activeFindings) {
    const current = state.intents.find((intent) => intent.id === finding.intentId);
    const currentCount = countByIntent.get(finding.intentId) || 0;
    const currentIsCleanAuto = Boolean(current && current.autoGenerated === true && isVerificationIntent(current) && currentCount <= 1);

    // 已经是一个干净的一对一 auto verify：只校正标题/proves 边，不迁。
    if (currentIsCleanAuto) {
      keptAuto.add(current.id);
      const expectedTitle = `验证：${String(finding.title || '').slice(0, 78)}`;
      if (current.title !== expectedTitle) {
        current.title = expectedTitle;
        changed = true;
      }
      if (!edgeExists(state, 'proves', current.id, finding.id)) {
        state.edges = state.edges.filter((edge) => !(edge.kind === 'proves' && edge.targetId === finding.id));
        pushEdge(state, 'proves', current.id, finding.id, now);
        changed = true;
      }
      continue;
    }

    // auto verify 里堆了多个 finding：保留第一个，其余迁到各自的专属 auto verify。
    if (current && current.autoGenerated === true && isVerificationIntent(current) && currentCount > 1 && !keptAuto.has(current.id)) {
      keptAuto.add(current.id);
      countByIntent.set(current.id, currentCount - 1);
      continue;
    }

    let sourceIntentId = '';
    let fromFactId = '';
    const factEdge = state.edges.find((edge) => edge.kind === 'derived_from' && edge.targetId === finding.id && String(edge.sourceId).startsWith('fact-'));
    if (factEdge) {
      fromFactId = factEdge.sourceId;
    } else if (current && current.autoGenerated === true) {
      const parent = sourceOfAuto(current);
      sourceIntentId = parent.sourceIntentId;
      fromFactId = parent.fromFactId;
    } else if (current) {
      sourceIntentId = current.id;
    }

    const verificationIntent = ensureVerificationIntent(state, {
      sourceIntentId: fromFactId ? '' : sourceIntentId,
      fromFactId,
      title: finding.title,
      now
    });
    finding.intentId = verificationIntent.id;
    countByIntent.set(verificationIntent.id, 1);
    state.edges = state.edges.filter((edge) => !(edge.kind === 'proves' && edge.targetId === finding.id));
    pushEdge(state, 'proves', verificationIntent.id, finding.id, now);
    changed = true;
  }

  if (changed) state.revision = Number(state.revision || 0) + 1;
  return changed;
}

function updateFinding(state, cmd, now) {
  const id = String(cmd.id || '');
  const finding = state.findings.find((item) => item.id === id && !item.deleted);
  if (!finding) fail('finding/not-found', `unknown finding ${id}`);
  if (cmd.title !== undefined) {
    const title = normalizeText(cmd.title);
    if (!title) fail('finding/title', 'finding title required');
    const duplicate = state.findings.find((item) => item.id !== id && normalizeText(item.title) === title && !item.deleted);
    if (duplicate) fail('finding/duplicate', `finding title "${title}" already exists as ${duplicate.id}`);
    finding.title = title;
  }
  if (cmd.severity !== undefined) {
    const severity = String(cmd.severity);
    if (!FINDING_SEVERITIES.has(severity)) fail('finding/severity', `unknown severity ${severity}`);
    finding.severity = severity;
  }
  if (cmd.intentId !== undefined) {
    const intentId = String(cmd.intentId || '');
    if (intentId) {
      const target = requireIntent(state, intentId);
      if (target.id !== finding.intentId) {
        const verificationIntent = ensureVerificationIntent(state, {
          sourceIntentId: target.id,
          title: finding.title,
          now
        });
        finding.intentId = verificationIntent.id;
        state.edges = state.edges.filter((edge) => !(edge.kind === 'proves' && edge.targetId === finding.id));
        pushEdge(state, 'proves', verificationIntent.id, finding.id, now);
      }
    } else {
      finding.intentId = '';
    }
  }
  if (cmd.dedupeKey !== undefined) finding.dedupeKey = normalizeText(cmd.dedupeKey);
  if (cmd.description !== undefined) finding.description = textOf(cmd.description);
  if (cmd.evidenceStatus !== undefined) finding.evidenceStatus = normalizeEvidenceStatus(cmd.evidenceStatus);
  if (cmd.impactProven !== undefined) finding.impactProven = textOf(cmd.impactProven);
  if (cmd.evidenceRefs !== undefined) finding.evidenceRefs = stringList(cmd.evidenceRefs);
  if (cmd.apiSources !== undefined || cmd.interfaceSources !== undefined || cmd.sourceFiles !== undefined || cmd.sources !== undefined) {
    finding.apiSources = stringList(cmd.apiSources ?? cmd.interfaceSources ?? cmd.sourceFiles ?? cmd.sources);
  }
  if (cmd.stepNotes !== undefined || cmd.stepExplanations !== undefined) {
    finding.stepNotes = stringList(cmd.stepNotes ?? cmd.stepExplanations);
  }
  if (cmd.stepResponses !== undefined || cmd.stepResponseBodies !== undefined) {
    finding.stepResponses = stringList(cmd.stepResponses ?? cmd.stepResponseBodies);
  }
  if (cmd.stepExpected !== undefined) {
    finding.stepExpected = stringList(cmd.stepExpected);
  }
  if (cmd.trafficRef !== undefined) finding.trafficRef = textOf(cmd.trafficRef);
  if (cmd.report !== undefined) finding.report = textOf(cmd.report);
  if (cmd.reproducibleSteps !== undefined || cmd.steps !== undefined) {
    const steps = stringList(cmd.reproducibleSteps ?? cmd.steps);
    assertReportReadySteps(steps);
    finding.reproducibleSteps = steps;
    finding.steps = steps;
    // Changing steps invalidates every per-step parallel array: keeping them
    // by index would attach an old response/note/expected to a new request.
    const align = (list, label) => {
      const values = Array.isArray(list) ? list.slice() : [];
      if (values.length === 0) return steps.map(() => '');
      if (values.length !== steps.length) {
        fail('finding/steps', `${label} must have the same length as reproducibleSteps (${values.length} vs ${steps.length})`);
      }
      return values;
    };
    const notesProvided = cmd.stepNotes !== undefined || cmd.stepExplanations !== undefined;
    const responsesProvided = cmd.stepResponses !== undefined || cmd.stepResponseBodies !== undefined;
    const expectedProvided = cmd.stepExpected !== undefined;
    finding.stepNotes = notesProvided ? align(finding.stepNotes, 'stepNotes') : steps.map(() => '');
    finding.stepResponses = responsesProvided ? align(finding.stepResponses, 'stepResponses') : steps.map(() => '');
    finding.stepExpected = expectedProvided ? align(finding.stepExpected, 'stepExpected') : steps.map(() => '');
  }
  if (cmd.remediation !== undefined) finding.remediation = textOf(cmd.remediation);
  if (cmd.riskAnalysis !== undefined) finding.riskAnalysis = textOf(cmd.riskAnalysis);
  if (cmd.affectedAssetId !== undefined) finding.affectedAssetId = textOf(cmd.affectedAssetId);
  if (cmd.affectedAssets !== undefined) finding.affectedAssets = stringList(cmd.affectedAssets);
  if (cmd.poc !== undefined) finding.poc = textOf(cmd.poc);
  if (cmd.counterevidence !== undefined) finding.counterevidence = textOf(cmd.counterevidence);
  if (cmd.confidence !== undefined) finding.confidence = Number.isFinite(cmd.confidence) ? cmd.confidence : undefined;
  if (cmd.noAssetReason !== undefined) finding.noAssetReason = textOf(cmd.noAssetReason);
  if (cmd.preconditions !== undefined) finding.preconditions = textOf(cmd.preconditions);
  if (cmd.scope !== undefined) finding.scope = textOf(cmd.scope);
  if (cmd.impactEvidence !== undefined) finding.impactEvidence = textOf(cmd.impactEvidence);
  if (cmd.validation !== undefined) finding.validation = cmd.validation && typeof cmd.validation === 'object' ? structuredClone(cmd.validation) : undefined;
  if (cmd.retest !== undefined) finding.retest = cmd.retest && typeof cmd.retest === 'object' ? structuredClone(cmd.retest) : undefined;
  finding.updatedAt = now;
  return finding;
}

function nonNegativeInt(value, fallback, max = Number.MAX_SAFE_INTEGER) {
  const n = Number(value);
  if (!Number.isFinite(n)) return fallback;
  return Math.min(max, Math.max(0, Math.round(n)));
}

/** Per-task execution budget. max=0 means unlimited. */
function normalizeTaskBudget(raw) {
  const source = raw && typeof raw === 'object' ? raw : {};
  return {
    maxCalls: nonNegativeInt(source.maxCalls, 24, 10000),
    maxMs: nonNegativeInt(source.maxMs, 15 * 60 * 1000, 24 * 60 * 60 * 1000),
    maxEvidence: nonNegativeInt(source.maxEvidence, 20, 10000),
    calls: nonNegativeInt(source.calls, 0, 1e9),
    timeMs: nonNegativeInt(source.timeMs, 0, 1e12),
    evidence: nonNegativeInt(source.evidence, 0, 1e9),
    exhausted: source.exhausted === true
  };
}

function budgetExhausted(budget, at = Date.now()) {
  if (!budget || typeof budget !== 'object') return false;
  if (budget.exhausted === true) return true;
  const calls = nonNegativeInt(budget.calls, 0)
  const timeMs = nonNegativeInt(budget.timeMs, 0)
  const evidence = nonNegativeInt(budget.evidence, 0)
  const maxCalls = nonNegativeInt(budget.maxCalls, 0)
  const maxMs = nonNegativeInt(budget.maxMs, 0)
  const maxEvidence = nonNegativeInt(budget.maxEvidence, 0)
  return Boolean(
    (maxCalls > 0 && calls >= maxCalls) ||
    (maxMs > 0 && timeMs >= maxMs) ||
    (maxEvidence > 0 && evidence >= maxEvidence)
  )
}

function markTaskBudgetDead(task, now) {
  task.state = 'dead'
  task.error = 'budget exhausted'
  task.workerId = ''
  task.leaseUntil = 0
  task.updatedAt = now
  if (task.budget) task.budget.exhausted = true
}

function applyQueue(state, cmd, now) {
  requireGoal(state);
  switch (cmd.op) {
    case 'push': {
      const intent = requireIntent(state, String(cmd.intentId || ''));
      if (INTENT_TERMINAL.has(intent.state)) fail('queue/intent-terminal', `intent ${intent.id} is ${intent.state}; cannot queue`);
      const active = activeTaskOfIntent(state, intent.id);
      if (active) return { task: active, reused: true };
      const task = {
        id: nextId(state, 'task'),
        intentId: intent.id,
        title: String(cmd.title || intent.title),
        state: 'pending',
        priority: Number.isFinite(cmd.priority) ? cmd.priority : intent.priority,
        workerId: '',
        leaseUntil: 0,
        attempts: 0,
        maxAttempts: Number.isFinite(cmd.maxAttempts) ? cmd.maxAttempts : 3,
        payload: typeof cmd.payload === 'object' && cmd.payload !== null ? structuredClone(cmd.payload) : {},
        budget: normalizeTaskBudget(cmd.budget || {
          maxCalls: cmd.maxCalls,
          maxMs: cmd.maxMs,
          maxEvidence: cmd.maxEvidence
        }),
        result: null,
        createdAt: now,
        updatedAt: now
      };
      state.queue.push(task);
      return { task, reused: false };
    }
    case 'claim': {
      const workerId = String(cmd.workerId || '');
      if (!workerId) fail('queue/worker', 'claim requires workerId');
      const held = activeTasksOfWorker(state, workerId);
      if (held.length > 0) return { task: held[0], reused: true };
      for (const task of state.queue) {
        if (task.state === 'pending' && budgetExhausted(task.budget, now)) {
          markTaskBudgetDead(task, now)
          refreshIntentFromTasks(state, task.intentId, now)
        }
      }
      const ready = state.queue
        .filter((task) => task.state === 'pending')
        .filter((task) => !budgetExhausted(task.budget, now))
        .filter((task) => {
          const intent = state.intents.find((item) => item.id === task.intentId);
          if (!intent || INTENT_TERMINAL.has(intent.state)) return false;
          return (intent.dependsOn || []).every((dep) => {
            const d = state.intents.find((item) => item.id === dep);
            return d && d.state === 'done';
          });
        })
        .sort((a, b) => b.priority - a.priority || a.createdAt - b.createdAt);
      if (ready.length === 0) return { task: null };
      const task = ready[0];
      if ((task.attempts || 0) >= task.maxAttempts) {
        task.state = 'dead';
        task.error = 'max attempts';
        task.updatedAt = now;
        refreshIntentFromTasks(state, task.intentId, now);
        return { task: null, dead: task.id };
      }
      task.state = 'claimed';
      task.workerId = workerId;
      task.leaseUntil = now + Number(cmd.leaseMs || 10 * 60 * 1000);
      task.attempts = (task.attempts || 0) + 1;
      task.updatedAt = now;
      const intent = state.intents.find((item) => item.id === task.intentId);
      if (intent && intent.state === 'open') {
        intent.state = 'running';
        intent.updatedAt = now;
      }
      return { task };
    }
    case 'assign': {
      const workerId = String(cmd.workerId || '');
      if (!workerId) fail('queue/worker', 'assign requires workerId');
      const task = requireTask(state, String(cmd.taskId || ''));
      if (task.state !== 'pending') fail('queue/assign-state', `task ${task.id} is ${task.state}, not pending`);
      if (budgetExhausted(task.budget, now)) {
        markTaskBudgetDead(task, now)
        refreshIntentFromTasks(state, task.intentId, now)
        return { task: null, dead: task.id }
      }
      const held = activeTasksOfWorker(state, workerId);
      if (held.length > 0 && held[0].id !== task.id) fail('queue/worker-busy', `worker ${workerId} already owns ${held[0].id}`);
      const intent = state.intents.find((item) => item.id === task.intentId);
      if (!intent || INTENT_TERMINAL.has(intent.state)) fail('queue/intent-terminal', `intent ${task.intentId} is not runnable`);
      task.state = 'claimed';
      task.workerId = workerId;
      task.leaseUntil = now + Number(cmd.leaseMs || 10 * 60 * 1000);
      task.attempts = (task.attempts || 0) + 1;
      task.updatedAt = now;
      if (intent.state === 'open') { intent.state = 'running'; intent.updatedAt = now; }
      return { task };
    }
    case 'complete': {
      const task = requireTask(state, String(cmd.taskId || ''));
      const workerId = String(cmd.workerId || '');
      if (workerId && task.workerId && workerId !== task.workerId) fail('queue/owner', `task ${task.id} belongs to ${task.workerId}`);
      if (!TASK_ACTIVE.has(task.state)) return { task, idempotent: true };
      task.state = 'done';
      task.workerId = '';
      task.leaseUntil = 0;
      task.result = {
        summary: String(cmd.summary ?? ''),
        evidenceIds: Array.isArray(cmd.evidenceIds) ? cmd.evidenceIds : [],
        findingIds: Array.isArray(cmd.findingIds) ? cmd.findingIds : []
      };
      task.updatedAt = now;
      refreshIntentFromTasks(state, task.intentId, now);
      const jobs = state.jobs?.[task.id];
      if (Array.isArray(jobs)) state.jobs[task.id] = [];
      return { task, cancelledJobs: Array.isArray(jobs) ? jobs : [] };
    }
    case 'fail': {
      const task = requireTask(state, String(cmd.taskId || ''));
      if (!TASK_ACTIVE.has(task.state)) return { task, idempotent: true };
      task.error = String(cmd.reason ?? '');
      task.updatedAt = now;
      if ((task.attempts || 0) >= task.maxAttempts) {
        task.state = 'dead';
        task.workerId = '';
        task.leaseUntil = 0;
      } else {
        task.state = 'pending';
        task.workerId = '';
        task.leaseUntil = 0;
      }
      refreshIntentFromTasks(state, task.intentId, now);
      const jobs = state.jobs?.[task.id];
      if (Array.isArray(jobs)) state.jobs[task.id] = [];
      return { task, cancelledJobs: Array.isArray(jobs) ? jobs : [] };
    }
    case 'renew': {
      const task = requireTask(state, String(cmd.taskId || ''));
      if (!TASK_ACTIVE.has(task.state) || task.state === 'pending') fail('queue/renew', `task ${task.id} is not active`);
      if (cmd.workerId && task.workerId && cmd.workerId !== task.workerId) fail('queue/owner', `task ${task.id} belongs to ${task.workerId}`);
      task.leaseUntil = now + Number(cmd.leaseMs || 10 * 60 * 1000);
      task.updatedAt = now;
      return { task };
    }
    case 'spend': {
      const task = requireTask(state, String(cmd.taskId || ''));
      if (cmd.workerId && task.workerId && cmd.workerId !== task.workerId) fail('queue/owner', `task ${task.id} belongs to ${task.workerId}`);
      if (!TASK_ACTIVE.has(task.state)) return { task, budget: task.budget || null, exhausted: true, idempotent: true };
      const budget = normalizeTaskBudget(task.budget);
      budget.calls += nonNegativeInt(cmd.calls, 0, 1e6);
      budget.timeMs += nonNegativeInt(cmd.timeMs, 0, 24 * 60 * 60 * 1000);
      budget.evidence += nonNegativeInt(cmd.evidence, 0, 1e6);
      budget.exhausted = budgetExhausted(budget, now);
      task.budget = budget;
      task.updatedAt = now;
      if (budget.exhausted) {
        markTaskBudgetDead(task, now);
        refreshIntentFromTasks(state, task.intentId, now);
      }
      return { task, budget, exhausted: budget.exhausted === true };
    }
    case 'bindJob': {
      const task = requireTask(state, String(cmd.taskId || ''));
      if (cmd.workerId && task.workerId && cmd.workerId !== task.workerId) fail('queue/owner', `task ${task.id} belongs to ${task.workerId}`);
      const jobId = String(cmd.jobId || '');
      if (!jobId) fail('queue/job', 'bindJob requires jobId');
      const current = Array.isArray(state.jobs?.[task.id]) ? state.jobs[task.id] : [];
      if (!current.includes(jobId)) current.push(jobId);
      state.jobs = { ...(state.jobs || {}), [task.id]: current };
      return { taskId: task.id, jobIds: current };
    }
    case 'reconcile': {
      const live = Array.isArray(cmd.liveWorkers) ? new Set(cmd.liveWorkers) : null;
      const changed = [];
      for (const task of state.queue) {
        if (task.state !== 'claimed' && task.state !== 'running') continue;
        const expired = Number(task.leaseUntil || 0) > 0 && Number(task.leaseUntil) <= now;
        const gone = live !== null && task.workerId && !live.has(task.workerId);
        if (!expired && !gone) continue;
        task.error = gone ? 'worker gone' : 'lease expired';
        task.updatedAt = now;
        if ((task.attempts || 0) >= task.maxAttempts) {
          task.state = 'dead';
        } else {
          task.state = 'pending';
        }
        task.workerId = '';
        task.leaseUntil = 0;
        refreshIntentFromTasks(state, task.intentId, now);
        changed.push(task.id);
      }
      return { changed };
    }
    default:
      fail('queue/op', `unknown queue op ${cmd.op}`);
  }
}

function applyGoal(state, cmd, now) {
  const goal = requireGoal(state);
  switch (cmd.op) {
    case 'set': {
      goal.target = String(cmd.target ?? goal.target);
      goal.objective = String(cmd.objective ?? goal.objective);
      goal.authorization = String(cmd.authorization ?? goal.authorization);
      if (cmd.workdir !== undefined) goal.workdir = String(cmd.workdir ?? '');
      if (cmd.targets !== undefined) goal.targets = stringList(cmd.targets);
      if (cmd.excludedTargets !== undefined) goal.excludedTargets = stringList(cmd.excludedTargets);
      goal.updatedAt = now;
      return goal;
    }
    case 'scope': {
      goal.targets = stringList(cmd.targets);
      goal.excludedTargets = stringList(cmd.excludedTargets);
      goal.scopeUpdatedAt = now;
      goal.updatedAt = now;
      return goal;
    }
    case 'prove': {
      const evidenceId = String(cmd.evidenceId || '');
      const evidence = state.facts.find((fact) => fact.id === evidenceId) || state.findings.find((finding) => finding.id === evidenceId);
      if (!evidence) fail('goal/proof', `unknown fact/finding ${evidenceId}`);
      if (!goal.proofs.some((proof) => proof.evidenceId === evidenceId)) {
        goal.proofs.push({ evidenceId, reason: String(cmd.reason ?? ''), at: now });
      }
      goal.updatedAt = now;
      return goal;
    }
    case 'complete': {
      const openIntents = state.intents.filter((intent) => !INTENT_TERMINAL.has(intent.state));
      if (openIntents.length > 0) fail('goal/open-intents', `goal still has ${openIntents.length} non-terminal intent(s)`);
      const activeQueue = state.queue.filter((task) => TASK_ACTIVE.has(task.state));
      if (activeQueue.length > 0) fail('goal/active-queue', `goal still has ${activeQueue.length} active queue task(s)`);
      if (!Array.isArray(goal.proofs) || goal.proofs.length === 0) fail('goal/unproven', 'goal has no evidence proof');
      goal.phase = 'completed';
      goal.updatedAt = now;
      return goal;
    }
    case 'stop': {
      goal.phase = 'stopped';
      goal.stoppedReason = { message: textOf(cmd.reason), at: now };
      goal.updatedAt = now;
      return goal;
    }
    case 'pause': {
      goal.paused = true;
      goal.pausedAt = now;
      goal.pauseReason = textOf(cmd.reason);
      goal.updatedAt = now;
      return goal;
    }
    case 'resume': {
      delete goal.paused;
      delete goal.pausedAt;
      delete goal.pauseReason;
      goal.updatedAt = now;
      return goal;
    }
    case 'reopen': {
      goal.phase = 'active';
      delete goal.blockedReason;
      delete goal.stoppedReason;
      delete goal.paused;
      delete goal.pausedAt;
      delete goal.pauseReason;
      goal.updatedAt = now;
      return goal;
    }
    case 'block': {
      const kind = String(cmd.kind || '');
      if (!['user', 'external', 'no-progress-rounds'].includes(kind)) {
        fail('goal/block-kind', 'goal block requires kind=user|external|no-progress-rounds; model opinion is not a blocker');
      }
      const openIntents = state.intents.filter((intent) => !INTENT_TERMINAL.has(intent.state));
      if (openIntents.length > 0) fail('goal/open-intents', `cannot block goal: ${openIntents.length} non-terminal intent(s) remain`);
      const activeQueue = state.queue.filter((task) => TASK_ACTIVE.has(task.state));
      if (activeQueue.length > 0) fail('goal/active-queue', `cannot block goal: ${activeQueue.length} active queue task(s) remain`);
      goal.phase = 'blocked';
      goal.blockedReason = { code: kind, message: String(cmd.reason ?? '') };
      goal.updatedAt = now;
      return goal;
    }
    default:
      fail('goal/op', `unknown goal op ${cmd.op}`);
  }
}

export function reduceV2(state, command) {
  const current = assertState(state);
  const now = Number.isFinite(command?.now) ? command.now : Date.now();
  const next = cloneState(current);
  let result;
  // stopped 是用户明确收工后的冻结态：除 goal 命令（reopen/stop）外，禁止继续写图。
  if (current.goal && current.goal.phase === 'stopped' && command?.type !== 'goal') {
    fail('goal/stopped', 'goal is stopped by the user; call pentest_reopen_goal first if the user explicitly asks to continue');
  }
  switch (command?.type) {
    case 'goal':
      result = applyGoal(next, command, now);
      break;
    case 'intent':
      result = applyIntent(next, command, now);
      break;
    case 'fact':
      result = applyFact(next, command, now);
      break;
    case 'asset':
      result = applyAsset(next, command, now);
      break;
    case 'finding':
      result = applyFinding(next, command, now);
      break;
    case 'coverage':
      result = applyCoverage(next, command, now);
      break;
    case 'digest':
      result = applyDigest(next, command, now);
      break;
    case 'edge': {
      requireGoal(next);
      const kind = String(command.kind || '');
      if (!kind) fail('edge/kind', 'edge kind required');
      result = pushEdge(next, kind, String(command.sourceId || ''), String(command.targetId || ''), now);
      break;
    }
    case 'queue':
      result = applyQueue(next, command, now);
      break;
    default:
      fail('command/type', `unknown command type ${command?.type}`);
  }
  next.revision = current.revision + 1;
  return { state: next, result };
}

/**
 * v3 writes use the v2 command contract through a lossless compatibility
 * bridge until Phase 1b extracts a native v3 reducer. This keeps all current
 * tools/handlers working while storage and read/report models are v3.
 */
export function reduce(state, command) {
  if (Number(state?.version) >= 3) return reduceV3State(state, command);
  return reduceV2(state, command);
}

export function view(state) {
  assertState(state);
  const intentNodes = state.intents.map((intent) => ({ ...intent, intentKind: intent.kind || 'recon', kind: 'intent' }));
  const factNodes = state.facts.map((fact) => ({ ...fact, kind: 'fact' }));
  const visibleFindings = state.findings.filter((finding) => finding.deleted !== true);
  const findingNodes = visibleFindings.map((finding) => ({ ...finding, kind: 'finding' }));
  return {
    goal: state.goal,
    nodes: [...intentNodes, ...factNodes, ...findingNodes],
    assets: state.assets,
    edges: state.edges,
    queue: state.queue,
    coverage: state.coverage,
    digests: state.digests,
    counts: {
      intents: state.intents.length,
      facts: state.facts.length,
      findings: visibleFindings.length,
      assets: state.assets.length,
      queue: state.queue.length
    },
    revision: state.revision
  };
}
