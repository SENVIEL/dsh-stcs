/**
 * Lineage compaction: remove synthetic verify directions produced by the v2
 * write contract. Findings are first-class; `directionId` may point at a real
 * direction or at the engagement goal when no real source direction exists.
 *
 * This is deliberately pure and idempotent. The v2 reducer can keep its
 * compatibility graph internally; it must never become persisted v3 lineage.
 */

function text(value) {
  return typeof value === 'string' ? value : value == null ? '' : String(value)
}

function isSynthetic(direction) {
  return direction?.legacyAuto === true || direction?.autoGenerated === true
}

export function compactSyntheticLineage(state) {
  if (!state || typeof state !== 'object' || Number(state.version) < 3) {
    return { changed: false, removed: [], state }
  }
  const directions = Array.isArray(state.directions) ? state.directions : []
  const synthetic = directions.filter(isSynthetic)
  if (synthetic.length === 0) return { changed: false, removed: [], state }

  const syntheticIds = new Set(synthetic.map((direction) => direction.id))
  const goalId = text(state.goal?.id)
  const edges = Array.isArray(state.edges) ? state.edges : []

  // Resolve the nearest real source for a synthetic wrapper. Prefer a
  // derived_from parent; fall back to the goal, never to another synthetic id.
  const sourceOf = new Map()
  for (const direction of synthetic) {
    const parent = edges.find((edge) => edge && edge.kind === 'derived_from' && edge.targetId === direction.id)
    const parentId = text(parent?.sourceId)
    sourceOf.set(direction.id, parentId && !syntheticIds.has(parentId) ? parentId : goalId)
  }

  const realIds = new Set(directions.filter((direction) => !syntheticIds.has(direction.id)).map((direction) => direction.id))
  const resolve = (id) => {
    const value = text(id)
    if (realIds.has(value)) return value
    if (syntheticIds.has(value)) {
      const source = sourceOf.get(value) || goalId
      return source && !syntheticIds.has(source) ? source : goalId
    }
    return value === goalId ? goalId : goalId
  }

  const findings = (state.findings || []).map((finding) => (
    finding.directionId && syntheticIds.has(finding.directionId)
      ? { ...finding, directionId: resolve(finding.directionId) }
      : finding
  ))
  const facts = (state.facts || []).map((fact) => (
    fact.directionId && syntheticIds.has(fact.directionId)
      ? { ...fact, directionId: resolve(fact.directionId) }
      : fact
  ))
  const queue = (state.queue || []).map((task) => {
    const directionId = task.directionId || task.intentId
    if (!syntheticIds.has(directionId)) return task
    return {
      ...task,
      directionId: null,
      intentId: undefined,
      state: ['pending', 'claimed', 'running'].includes(task.state) ? 'dead' : task.state,
      error: task.error || 'lineage migrated: synthetic direction removed'
    }
  })
  const nextEdges = edges.filter((edge) => (
    edge && !syntheticIds.has(edge.sourceId) && !syntheticIds.has(edge.targetId)
  ))
  const nextDirections = directions.filter((direction) => !syntheticIds.has(direction.id))
  const changed = nextDirections.length !== directions.length ||
    findings.some((finding, index) => finding !== (state.findings || [])[index]) ||
    facts.some((fact, index) => fact !== (state.facts || [])[index]) ||
    queue.some((task, index) => task !== (state.queue || [])[index]) ||
    nextEdges.length !== edges.length

  if (!changed) return { changed: false, removed: [], state }
  return {
    changed: true,
    removed: [...syntheticIds],
    state: {
      ...state,
      directions: nextDirections,
      findings,
      facts,
      queue,
      edges: nextEdges,
      counters: {
        ...(state.counters || {}),
        intent: Math.max(Number(state.counters?.intent) || 0, nextDirections.length)
      }
    }
  }
}

export function compactSyntheticLineageInPlace(state) {
  const out = compactSyntheticLineage(state)
  return out
}
