/**
 * DSH pentest v2 — projection + event snapshot.
 *
 * 唯一职责：把 state 纯函数映射成 UI 投影。禁止读外部状态、禁止写。
 * UI 与 DB 一致性靠“每次提交后发完整快照事件”，而不是增量 fold。
 */

import { view } from './state.js';
import { toViewModel } from './view-model-v3.js';
import { applyProjectionPatch } from './projection-diff.js';
import { deriveCoverageFindings, enrichFindingsFromEvidence } from './v4/finding-fields.js';
import { attachAllStepResponses } from './v4/step-responses.js';
import { auditStateOf, categoryOfAuditState } from './v4/policy.js';
import { latestValidationFor } from './v4/validations.js';

export const SNAPSHOT_EVENT = 'plugin:pentest/state';
export const LEGACY_SNAPSHOT_EVENT = 'pentest/state';

/** 边界统一清洗：undefined 不进 projection / 日志 / 工具输出。 */
export function jsonSafe(value) {
  if (value === undefined) return null;
  return JSON.parse(JSON.stringify(value));
}

function asArray(value) {
  return Array.isArray(value) ? value : [];
}

function asText(value) {
  return typeof value === 'string' ? value : (value === undefined || value === null ? '' : String(value));
}

function shortTitle(value, max = 88) {
  const first = asText(value).split(/[\n。！？!?]/)[0].replace(/\s+/g, ' ').trim();
  return first.length > max ? `${first.slice(0, max - 1)}…` : first;
}

function evidenceStatusOf(value) {
  const raw = asText(value).toLowerCase();
  if (['confirmed', 'verified', 'reproduced', '已验证', '已确认', '已复现'].includes(raw)) return 'confirmed';
  if (['likely', 'probable', '很可能', '强证据'].includes(raw)) return 'likely';
  return 'unverified';
}

/** v2 节点 → 旧 UI 能安全消费的节点（旧 UI 会直接读 finding.steps.length）。 */
function uiCompatNode(node) {
  if (node.kind === 'finding') {
    return {
      ...node,
      description: asText(node.description),
      steps: asArray(node.steps).length > 0 ? asArray(node.steps) : asArray(node.reproducibleSteps),
      evidenceRefs: asArray(node.evidenceRefs),
      evidenceStatus: evidenceStatusOf(node.evidenceStatus),
      remediation: asText(node.remediation),
      trafficRef: asText(node.trafficRef),
      report: asText(node.report)
    };
  }
  if (node.kind === 'fact') {
    return {
      ...node,
      factKind: asText(node.factKind) || 'info',
      confidence: typeof node.confidence === 'number' ? node.confidence : node.confidence === 'high' ? 0.9 : node.confidence === 'medium' ? 0.6 : 0.3
    };
  }
  return node;
}

function timelineNodes(nodes) {
  const list = (Array.isArray(nodes) ? nodes : []).map(uiCompatNode);
  const created = list
    .map((node, index) => ({ node, index }))
    .sort((a, b) => {
      const at = Number(a.node.createdAt) || 0;
      const bt = Number(b.node.createdAt) || 0;
      if (at !== bt) return at - bt;
      return a.index - b.index;
    });
  const seqById = new Map(created.map(({ node }, index) => [node.id, index + 1]));
  return list.map((node) => ({
    ...node,
    seq: Number.isSafeInteger(node.seq) && node.seq > 0 ? node.seq : (seqById.get(node.id) ?? 0),
    at: Number(node.at) > 0 ? node.at : (Number(node.createdAt) || 0)
  }));
}

function isVerificationIntentNode(node) {
  return node?.kind === 'intent' && (node.intentKind === 'verify' || node.intentKind === 'exploit');
}

/**
 * 旧图回放修复：finding 如果直接挂在侦察 intent 下，UI 会呈现
 * “一个侦察意图产出一堆漏洞”。这里在投影层补一个虚拟 verify intent，
 * 边改为 recon -> verify(derived_from) -> finding(proves)。
 * 不写 state；新的写入在 state 层已经直接生成真实 verify intent。
 */
export function projectFindingLineage(nodesInput, edgesInput, goalId = '') {
  const nodes = asArray(nodesInput).map((node) => ({ ...node }));
  const edges = asArray(edgesInput).map((edge) => ({ ...edge }));
  const intentById = new Map(nodes.filter((node) => node.kind === 'intent').map((node) => [node.id, node]));
  const findingNodes = nodes.filter((node) => node.kind === 'finding');
  const extraNodes = [];
  const extraEdges = [];
  for (const finding of findingNodes) {
    const source = intentById.get(finding.intentId);
    const factEdge = edges.find((edge) => edge.kind === 'derived_from' && edge.targetId === finding.id && String(edge.sourceId).startsWith('fact-'));
    const currentDerivedFromFact = factEdge
      ? edges.some((edge) => edge.kind === 'derived_from' && edge.sourceId === factEdge.sourceId && edge.targetId === finding.intentId)
      : false;
    // 已挂在该 fact 派生的 verify intent 下：真实链路已正确。
    if (isVerificationIntentNode(source) && (!factEdge || currentDerivedFromFact)) continue;
    const virtualId = `virtual-verify-${finding.id}`;
    const createdAt = Number(finding.createdAt) || Date.now();
    extraNodes.push({
      id: virtualId,
      kind: 'intent',
      intentKind: 'verify',
      title: `验证：${asText(finding.title).slice(0, 78)}`,
      detail: '验证该事实并保存可复现的完整 HTTP 请求包。',
      doneWhen: '结论被请求/响应证据证实或否证',
      state: 'done',
      stateReason: 'finding recorded',
      priority: 3,
      autoGenerated: true,
      virtual: true,
      createdAt,
      updatedAt: createdAt
    });
    // 有 fact 时验证链落在 fact 上；没有 fact 才挂到 goal。
    const sourceId = factEdge?.sourceId || goalId || (source?.id && isVerificationIntentNode(source) ? source.id : '');
    if (sourceId) extraEdges.push({ id: `virtual-derived-${finding.id}`, kind: 'derived_from', sourceId, targetId: virtualId, createdAt });
    extraEdges.push({ id: `virtual-proves-${finding.id}`, kind: 'proves', sourceId: virtualId, targetId: finding.id, createdAt });
    for (let index = edges.length - 1; index >= 0; index -= 1) {
      if (edges[index].kind === 'proves' && edges[index].targetId === finding.id) edges.splice(index, 1);
    }
    finding.intentId = virtualId;
    finding.intentKind = 'verify';
  }
  return { nodes: [...nodes, ...extraNodes], edges: [...edges, ...extraEdges] };
}

/**
 * A finding necessarily gets an auto-generated verify intent in state. That
 * wrapper is useful for lineage, but rendering it as just another planner
 * intent makes the graph look like "every intent produced a vulnerability".
 * Collapse those synthetic intents and attach each finding to its real source
 * (the fact/intent named on its derived_from edge) instead.
 */
function collapseAutoVerification(nodesInput, edgesInput, goalId = '') {
  const nodes = asArray(nodesInput).map((node) => ({ ...node }));
  const edges = asArray(edgesInput).map((edge) => ({ ...edge }));
  const autoIds = new Set(nodes.filter((node) => node.kind === 'intent' && node.autoGenerated === true).map((node) => node.id));
  if (autoIds.size === 0) return { nodes, edges };
  const sourceOf = new Map();
  for (const node of nodes) {
    if (!autoIds.has(node.id)) continue;
    if (node.sourceFactId && nodes.some((candidate) => candidate.id === node.sourceFactId)) sourceOf.set(node.id, node.sourceFactId);
  }
  for (const edge of edges) {
    if (edge.kind === 'derived_from' && autoIds.has(edge.targetId) && !sourceOf.has(edge.targetId)) {
      sourceOf.set(edge.targetId, edge.sourceId);
    }
  }
  const keptNodes = nodes.filter((node) => !autoIds.has(node.id));
  const keptEdges = edges.filter((edge) => !autoIds.has(edge.sourceId) && !autoIds.has(edge.targetId));
  for (const finding of keptNodes) {
    if (finding.kind !== 'finding' || !autoIds.has(finding.intentId)) continue;
    const autoIntentId = finding.intentId;
    const autoIntent = nodes.find((node) => node.id === autoIntentId && node.kind === 'intent');
    const sourceId = sourceOf.get(autoIntentId) || goalId;
    finding.lineageIntentId = autoIntentId;
    finding.lineageIntentTitle = autoIntent ? String(autoIntent.title || autoIntent.id || '') : '';
    finding.intentId = sourceId;
    finding.autoLineage = true;
    finding.lineageUnbound = !sourceId || sourceId === goalId;
    const validationOk = Boolean(finding.validation && finding.validation.verdict === 'reproduced');
    const evidenceRefs = Array.isArray(finding.evidenceRefs) ? finding.evidenceRefs : [];
    finding.evidenceVerified = validationOk || evidenceRefs.length > 0;
    if (sourceId && !keptEdges.some((edge) => edge.kind === 'proves' && edge.sourceId === sourceId && edge.targetId === finding.id)) {
      keptEdges.push({ id: `collapsed-proves-${finding.id}`, kind: 'proves', sourceId, targetId: finding.id, createdAt: finding.createdAt });
    }
  }
  return { nodes: keptNodes, edges: keptEdges };
}

export function toProjection(state) {
  if (Number(state?.version) >= 4) {
    state = attachAllStepResponses(deriveCoverageFindings(enrichFindingsFromEvidence(state)));
    // v4 keeps execution in `tasks`; the shared view model reads `queue`.
    const tasks = Array.isArray(state.tasks) ? state.tasks : [];
    const directions = (Array.isArray(state.directions) ? state.directions : [])
      .filter((item) => item && item.deleted !== true)
      .map((item) => ({
      ...item,
      title: item.title || item.question || '',
      summary: item.summary || item.question || '',
      detail: item.detail || item.question || ''
    }));
    const facts = (Array.isArray(state.facts) ? state.facts : []).map((item) => ({
      ...item,
      title: item.title || item.answer || '',
      summary: item.summary || item.answer || '',
      detail: item.detail || item.answer || ''
    }));
    const validations = Array.isArray(state.validations) ? state.validations : [];
    const directionById = new Map(directions.map((item) => [item.id, item]));
    const findings = (Array.isArray(state.findings) ? state.findings : [])
      .filter((item) => item.deleted !== true && item.severity !== 'info')
      .map((item) => {
        const validation = latestValidationFor(validations, item.id);
        // ONE authoritative classification, computed only here. Every UI
        // count and every backend candidate selection must consume these two
        // fields instead of re-deriving from status/approval/impactProven.
        const auditState = auditStateOf(item, validations);
        return {
          ...item,
          // Override any stale category the model may have written.
          category: categoryOfAuditState(auditState),
          auditState,
          title: item.title || shortTitle(item.claim),
          summary: item.summary || shortTitle(item.claim),
          detail: item.detail || item.claim || '',
          evidenceStatus: validation?.verdict === 'reproduced' ? 'confirmed'
            : validation?.verdict === 'not_reproduced' ? 'unverified' : (item.status || 'unverified'),
          validation: validation ? {
            verdict: validation.verdict,
            validator: validation.validator,
            notes: validation.notes,
            evidenceRefs: validation.evidenceIds || [],
            at: validation.at
          } : undefined
        };
      });
    return toViewModel({
      ...state,
      goal: state.goal ? { ...state.goal, paused: state.goal.phase === 'paused' } : state.goal,
      directions,
      facts,
      findings,
      queue: tasks.map((task) => ({
        ...task,
        title: shortTitle(task.title || directionById.get(task.directionId)?.question || task.id, 120),
        intentId: task.directionId || '',
        directionId: task.directionId || null
      }))
    });
  }
  if (Number(state?.version) >= 3) return toViewModel(state);
  const base = view(state);
  // 保留每个 finding 专属的 auto verify intent，不再折叠回源 intent，
  // 否则 UI 会重新出现「一个意图挂一堆漏洞」。
  const compact = projectFindingLineage(base.nodes, base.edges, base.goal?.id || '');
  // 长任务的 digest 是图的压缩节点；旧 UI 已有 kind=digest 渲染。
  const digestNodes = asArray(base.digests).map((digest) => ({
    ...digest,
    kind: 'digest',
    detail: asText(digest.summary),
    memberIds: asArray(digest.factIds),
    createdAt: Number(digest.createdAt) || 0
  }));
  // 旧 UI 时间线按 node.seq 排序、用 node.at 显示时刻。v2 每个节点都有 createdAt，
  // 这里统一补上稳定创建序号和真实时间；目标固定 seq=0，因此始终在时间线最下面。
  // 压缩节点必须属于一条可见链路：把 digest 挂到产出其成员事实的源 intent。
  // 旧 UI 默认隐藏事实；若只连 digest→fact，压缩节点会看起来完全孤立。
  const digestEdges = []
  const nodeById = new Map([...compact.nodes, ...digestNodes].map((node) => [node.id, node]))
  for (const digest of digestNodes) {
    const memberIds = new Set(asArray(digest.factIds))
    const sourceIntents = new Set()
    for (const edge of compact.edges) {
      if (edge.kind !== 'yields' || !memberIds.has(edge.targetId)) continue
      const source = nodeById.get(edge.sourceId)
      if (source?.kind === 'intent') sourceIntents.add(edge.sourceId)
    }
    if (sourceIntents.size === 0 && base.goal?.id) sourceIntents.add(base.goal.id)
    for (const sourceId of sourceIntents) {
      const id = `digest-link-${digest.id}-${sourceId}`
      if (digestEdges.some((edge) => edge.id === id)) continue
      digestEdges.push({
        id,
        kind: 'yields',
        sourceId,
        targetId: digest.id,
        createdAt: Number(digest.createdAt) || 0
      })
    }
  }
  const allEdges = [...compact.edges, ...digestEdges]
  const nodes = timelineNodes([...compact.nodes, ...digestNodes]);
  const intents = nodes.filter((node) => node.kind === 'intent');
  const facts = nodes.filter((node) => node.kind === 'fact');
  const findings = nodes.filter((node) => node.kind === 'finding');
  return jsonSafe({
    goal: base.goal,
    nodes,
    assets: asArray(base.assets).map((item) => ({
      ...item,
      title: item.title || item.value || item.type || item.id || 'asset',
      summary: item.summary || item.value || '',
      detail: item.detail || item.meta || item.value || ''
    })),
    edges: allEdges,
    queue: base.queue,
    coverage: base.coverage,
    digests: base.digests,
    intents,
    facts,
    findings,
    counts: {
      ...base.counts,
      intents: intents.length,
      facts: facts.length,
      findings: findings.length
    },
    revision: state.revision,
    members: [],
    memberNames: {}
  });
}

/** 事件载荷：完整投影 + revision。UI 直接替换，不 fold。 */
export function snapshotEvent(state, options = {}) {
  return {
    type: SNAPSHOT_EVENT,
    ...(options.force === true ? { force: true } : {}),
    data: {
      revision: state.revision,
      state: toProjection(state)
    }
  };
}

/**
 * 旧 projection 的 apply 语义：收到 snapshot 就整体替换。
 * 保留旧状态字段（goal/nodes/...），不依赖任何增量顺序。
 */
export function applySnapshot(previous, event) {
  if (!event || (event.type !== SNAPSHOT_EVENT && event.type !== LEGACY_SNAPSHOT_EVENT)) return previous;
  const value = event.data?.patch
    ? applyProjectionPatch(previous, event.data.patch)
    : event.data?.state;
  if (!value || typeof value !== 'object') return previous;
  const nextRevision = Number(event.data?.revision ?? value.revision ?? 0);
  const previousRevision = Number(previous?.revision ?? 0);
  if (nextRevision < previousRevision) return previous;
  if (Number(value.version) >= 3) {
    const nodes = timelineNodes(asArray(value.nodes));
    const intents = nodes.filter((node) => node.kind === 'intent');
    const facts = nodes.filter((node) => node.kind === 'fact');
    const findings = nodes.filter((node) => node.kind === 'finding');
    return {
      ...value,
      nodes,
      intents,
      facts,
      findings,
      counts: {
        ...(value.counts || {}),
        intents: intents.length,
        facts: facts.length,
        findings: findings.length,
        assets: asArray(value.assets).length,
        queue: asArray(value.queue).length
      },
      revision: nextRevision
    };
  }
  // 旧快照没有 seq/at；apply 时补齐，重启回放也能修复时间线和目标排序。
  // 同时修复旧 finding 直接挂 recon intent 的血缘展示。
  const lineage = projectFindingLineage(value.nodes, value.edges, value.goal?.id || '');
  // 同样保留每个 finding 的专属 auto verify intent；否则重启回放旧快照时
  // UI 又把多条 finding 折叠回同一个源 intent。
  const compact = lineage;
  const nodes = timelineNodes(compact.nodes);
  const intents = nodes.filter((node) => node.kind === 'intent');
  const facts = nodes.filter((node) => node.kind === 'fact');
  const findings = nodes.filter((node) => node.kind === 'finding');
  return {
    ...value,
    nodes,
    edges: compact.edges,
    intents,
    facts,
    findings,
    counts: {
      ...(value.counts || {}),
      intents: intents.length,
      facts: facts.length,
      findings: findings.length,
      assets: asArray(value.assets).length,
      queue: asArray(value.queue).length
    },
    revision: nextRevision
  };
}
