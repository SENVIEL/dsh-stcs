/**
 * Phase 1b write bridge: v3 state <-> v2 command contract.
 *
 * v3 is the canonical read/report model. Until a native v3 reducer is
 * extracted, the existing, well-tested v2 command layer writes through a
 * temporary v2 compatibility graph (one synthetic verify per finding), then
 * migrates the result back to v3. Key point: synthetic nodes never persist in
 * v3 and v3 read paths never repair.
 */
import { reduceV2, StateError } from './state.js'
import { migrateToV3 } from './migrate-v3.js'
import { enrichFindingsFromEvidence } from './v4/finding-fields.js'

function text(value) {
  return typeof value === 'string' ? value : value == null ? '' : String(value)
}

function verifyTitle(finding) {
  return `验证：${text(finding?.title).replace(/\s+/g, ' ').trim().slice(0, 78)}`
}

function rawSteps(finding) {
  const steps = Array.isArray(finding?.steps) ? finding.steps : []
  return steps.map((step) => text(step?.request ?? step))
}

function stepNotes(finding) {
  const steps = Array.isArray(finding?.steps) ? finding.steps : []
  return steps.map((step) => text(step?.note))
}

/**
 * Build a v2 command-compatible graph. This graph is temporary and is never
 * written to storage; synthetic verify intents are removed by migrateToV3.
 */
export function v3ToV2Compat(state) {
  state = enrichFindingsFromEvidence(state)
  const compat = structuredClone(state)
  compat.version = 2
  const intents = (state.directions || []).map((direction) => ({
    ...direction,
    kind: direction.kind || 'recon'
  }))
  const edges = (state.edges || []).map((edge) => ({ ...edge }))
  const findings = (state.findings || []).map((finding) => {
    const verifyId = `verify-${finding.id}`
    const raw = rawSteps(finding)
    const notes = stepNotes(finding)
    const validation = (state.validations || []).find((item) => item.findingId === finding.id)
    const directionId = finding.directionId || ''
    const sourceId = directionId || (state.goal?.id || '')
    intents.push({
      id: verifyId,
      title: verifyTitle(finding),
      detail: 'finding validation wrapper (temporary v2 write bridge)',
      doneWhen: 'finding recorded',
      kind: 'verify',
      state: 'done',
      stateReason: 'finding recorded',
      priority: 3,
      autoGenerated: true,
      dependsOn: [],
      createdAt: Number(finding.createdAt) || 0,
      updatedAt: Number(finding.updatedAt) || Number(finding.createdAt) || 0
    })
    if (sourceId) edges.push({ id: `bridge-derived-${finding.id}`, kind: 'derived_from', sourceId, targetId: verifyId })
    edges.push({ id: `bridge-proves-${finding.id}`, kind: 'proves', sourceId: verifyId, targetId: finding.id })
    const compatFinding = {
      ...finding,
      title: text(finding.title || finding.claim),
      description: text(finding.description || finding.claim),
      riskAnalysis: text(finding.riskAnalysis),
      remediation: text(finding.remediation),
      evidenceStatus: validation?.verdict === 'reproduced' ? 'confirmed'
        : validation?.verdict === 'not_reproduced' ? 'unverified'
          : (finding.status || 'unverified'),
      intentId: verifyId,
      steps: raw,
      reproducibleSteps: raw,
      stepNotes: notes,
      stepResponses: (finding.steps || []).map((step) => text(step?.response)),
      stepExpected: (finding.steps || []).map((step) => text(step?.expected)),
      validation: validation
        ? {
            verdict: validation.verdict,
            validator: validation.validator,
            notes: validation.notes,
            // Must survive the v2 round-trip: dropping this made every v3 write
            // silently erase independent-validation evidence.
            evidenceRefs: Array.isArray(validation.evidenceRefs) ? validation.evidenceRefs.slice() : [],
            at: validation.at
          }
        : undefined
    }
    delete compatFinding.evidenceIds
    delete compatFinding.validationId
    delete compatFinding.stepsStructured
    return compatFinding
  })
  const facts = (state.facts || []).map((fact) => ({
    ...fact,
    intentId: fact.directionId || fact.intentId || ''
  }))
  const queue = (state.queue || []).map((task) => ({
    ...task,
    intentId: task.directionId || task.intentId || ''
  }))
  const counters = { ...(state.counters || {}) }
  counters.intent = Math.max(Number(counters.intent) || 0, intents.length)
  counters.finding = Math.max(Number(counters.finding) || 0, findings.length)
  return {
    ...compat,
    version: 2,
    intents,
    findings,
    facts,
    queue,
    edges,
    counters
  }
}

function findResultInV3(result, state) {
  if (!result || typeof result !== 'object') return result
  const id = text(result.id)
  if (id) {
    for (const collection of [state.findings, state.directions, state.facts, state.assets, state.retests, state.validations]) {
      const match = (collection || []).find((item) => item.id === id)
      if (match) return match
    }
  }
  if (result.task && typeof result.task === 'object') {
    const task = (state.queue || []).find((item) => item.id === result.task.id)
    if (task) return { ...result, task }
  }
  if (result.fact && typeof result.fact === 'object') {
    const fact = (state.facts || []).find((item) => item.id === result.fact.id)
    if (fact) return { ...result, fact }
  }
  return result
}

function adaptResult(result, state) {
  const adapted = findResultInV3(result, state)
  if (adapted && adapted === result) return adapted
  // Compatibility alias for callers that still read finding.intentId.
  if (adapted && Array.isArray(state.findings) && state.findings.some((finding) => finding.id === adapted.id)) {
    const validation = (state.validations || []).find((item) => item.findingId === adapted.id)
    return {
      ...adapted,
      intentId: adapted.directionId || '',
      ...(validation ? {
        validation: {
          verdict: validation.verdict,
          validator: validation.validator,
          notes: validation.notes,
          evidenceRefs: Array.isArray(validation.evidenceRefs) ? validation.evidenceRefs : [],
          at: validation.at
        }
      } : {})
    }
  }
  return adapted
}

export function reduceV3State(state, command) {
  const compat = v3ToV2Compat(state)
  const out = reduceV2(compat, command)
  const migrated = migrateToV3(out.state, { now: Number(command?.now) || Date.now() })
  return {
    state: migrated.state,
    result: adaptResult(out.result, migrated.state),
    migrationStats: migrated.stats
  }
}

export { StateError }
